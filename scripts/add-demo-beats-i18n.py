def unflatten(flat: dict) -> dict:
    """Convert dotted keys (`nova.open.narration`) into nested dicts."""
    out: dict = OrderedDict()
    for k, v in flat.items():
        parts = k.split(".")
        cur = out
        for p in parts[:-1]:
            cur = cur.setdefault(p, OrderedDict())
        cur[parts[-1]] = v
    return out


def main() -> None:
    # Sanity: every locale has the same set of leaf keys as English.
    en_keys = set(EN)
    for loc, table in PER_LOCALE.items():
        if loc == "en":
            continue
        missing = en_keys - set(table)
        extra = set(table) - en_keys
        if missing or extra:
            raise SystemExit(
                f"locale {loc} key mismatch — missing={sorted(missing)} extra={sorted(extra)}"
            )

    for loc, flat in PER_LOCALE.items():
        path = MSG / f"{loc}.json"
        data = json.loads(path.read_text(encoding="utf-8"))
        # Replace any prior `demoBeats` block — this script is the
        # authoritative source for that namespace.
        data["demoBeats"] = unflatten(flat)
        # Pretty-print with 2-space indent matching the surrounding
        # files; ensure_ascii=False so non-Latin scripts stay readable.
        path.write_text(
            json.dumps(data, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        print(f"wrote {path.relative_to(ROOT)}  ({len(flat)} keys)")


if __name__ == "__main__":
    main()
